package xyz.gabriwar.warpedpixeldungeon.items.catching;

import xyz.gabriwar.warpedpixeldungeon.items.Item;
import xyz.gabriwar.warpedpixeldungeon.sprites.ItemSpriteSheet;

/**
 * An old boot, sodden and full of weed: what a fishing rod brings up now and then instead of a fish
 * (FishingRules.Junk.BOOT), anywhere but the caves. Worth a coin, and a story.
 */
public class OldBoot extends Item {

	{
		image = ItemSpriteSheet.OLD_BOOT;
		stackable = true;
		bones = false;
	}

	@Override
	public boolean isUpgradable(){
		return false;
	}

	@Override
	public boolean isIdentified(){
		return true;
	}

	@Override
	public int value(){
		return quantity;
	}
}
