package xyz.gabriwar.warpedpixeldungeon.items.misc;

import xyz.gabriwar.warpedpixeldungeon.items.artifacts.Artifact;

// Sprouted's misc equippable items (AutoPotion, Spectacles, etc.)
// In modern shattered, these use the Artifact slot system since
// KindofMisc only handles Artifact and Ring slots explicitly.
public abstract class MiscEquippable extends Artifact {

	{
		unique = true;
	}

	@Override
	public boolean isUpgradable() {
		return false;
	}

	@Override
	public boolean isIdentified() {
		return true;
	}
}
